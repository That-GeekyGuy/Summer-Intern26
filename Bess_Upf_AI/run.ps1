# Parse .env into hashtable for summary
$EnvVars = @{}
Get-Content .env | Where-Object { $_ -match '^[^#\s].*=.*' } | ForEach-Object {
    $k, $v = $_ -split '=', 2
    $EnvVars[$k.Trim()] = $v.Trim()
}

# ─────────────────────────────────────────────────────────────────────────────
# 3 -- Dev TLS certificates
# ─────────────────────────────────────────────────────────────────────────────
Step "3/9  Dev TLS certificates"

if ((Test-Path 'certs\server.crt') -and (Test-Path 'certs\server.key')) {
    Info "Certificates exist -- skipping."
} else {
    $hostname = if ($EnvVars['CADDY_HOSTNAME']) { $EnvVars['CADDY_HOSTNAME'] } else { 'localhost' }
    Info "Generating self-signed certificate for $hostname..."
    New-Item -ItemType Directory -Force -Path 'certs' | Out-Null
    & openssl req -x509 -newkey rsa:4096 `
        -keyout "certs\server.key" -out "certs\server.crt" `
        -days 365 -nodes `
        -subj "/CN=$hostname/O=BESS-UPF Dev/C=XX" `
        -addext "subjectAltName=DNS:$hostname,DNS:localhost,IP:127.0.0.1"
    Info "Certificates written to certs\"
}

# ─────────────────────────────────────────────────────────────────────────────
# 4 -- Git LFS pull (large model files)
# ─────────────────────────────────────────────────────────────────────────────
Step "4/9  Model artifacts"

if (-not (Test-Path 'models\random_forest.joblib')) {
    Info "Fetching model artifacts from MinIO..."
    & bash scripts/fetch-models.sh models
    if ($LASTEXITCODE -eq 0) {
        Info "Model artifacts fetched."
    } else {
        Warn "MinIO fetch failed -- Tier 2 sklearn/ML detection will start in degraded mode."
        Warn "Ensure the stack is up and run: bash scripts/fetch-models.sh"
    }
} else {
    Info "random_forest.joblib present -- skipping MinIO fetch."
}

# ─────────────────────────────────────────────────────────────────────────────
# 5 -- GPU detection -> model selection
# ─────────────────────────────────────────────────────────────────────────────
Step "5/9  GPU / LLM selection"

$ComposeBase  = @('-f', 'docker-compose.base.yml', '-f', 'docker-compose.core.yml', '-f', 'docker-compose.ml.yml')
$DevCompose   = @('-f', 'dev/docker-compose.yml')
$ComposeFiles = $ComposeBase
$Mode = 'cpu'

function Test-GpuAvailable {
    if (-not (Get-Command nvidia-smi -ErrorAction SilentlyContinue)) { Warn "nvidia-smi not found."; return $false }
    & nvidia-smi 2>&1 | Out-Null
    if ($LASTEXITCODE -ne 0) { Warn "nvidia-smi failed (driver issue?)."; return $false }
    $di = & docker info 2>&1
    if ($di -notmatch 'nvidia') {
        Warn "GPU found but Docker nvidia runtime not configured."
        Warn "Fix: enable GPU support in Docker Desktop settings."
        return $false
    }
    return $true
}

function Set-GpuModel {
    $vramMb = (& nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits 2>$null |
        Select-Object -First 1).Trim()
    $vramGb = [int]([int]$vramMb / 1024)
    Info "GPU VRAM: ${vramGb} GB"
    if ($vramGb -ge 24) {
        Info ">= 24 GB -> Qwen/Qwen3-14B FP16 (max_len 8192)"
        $env:VLLM_MODEL = 'Qwen/Qwen2.5-14B-Instruct'; $env:VLLM_MAX_MODEL_LEN = '8192'; $env:VLLM_GPU_MEM_UTIL = '0.90'
    } elseif ($vramGb -ge 13) {
        Info "13-23 GB -> Qwen/Qwen3-8B FP16 (max_len 8192)"
        $env:VLLM_MODEL = 'Qwen/Qwen2.5-7B-Instruct';  $env:VLLM_MAX_MODEL_LEN = '8192'; $env:VLLM_GPU_MEM_UTIL = '0.90'
    } elseif ($vramGb -ge 8) {
        Info "8-12 GB -> Qwen/Qwen3-8B INT4 (max_len 3200)"
        $env:VLLM_MODEL = 'Qwen/Qwen2.5-7B-Instruct';  $env:VLLM_MAX_MODEL_LEN = '3200'; $env:VLLM_GPU_MEM_UTIL = '0.90'
    } else {
        Warn "VRAM ${vramGb} GB < 8 GB -- falling back to CPU/Ollama."
        return $false
    }
    $hfToken = $EnvVars['HF_TOKEN']
    if (-not $hfToken -or $hfToken -match '^CHANGE_ME') {
        $hfInput = Read-Host "[run] Enter HF_TOKEN for vLLM (or Enter to use CPU/Ollama)"
        if ($hfInput) {
            $env:HF_TOKEN = $hfInput
            (Get-Content .env) -replace '^HF_TOKEN=.*', "HF_TOKEN=$hfInput" | Set-Content .env
            Info "HF_TOKEN saved to .env."
        } else {
            Warn "No token provided -- falling back to CPU/Ollama."; return $false
        }
    }
    return $true
}

if ((Test-GpuAvailable) -and (Set-GpuModel)) {
    $Mode = 'gpu'
    $ComposeFiles = $ComposeBase + @('-f', 'docker-compose.gpu.yml')
    Info "LLM mode: GPU -> vLLM  model=$($env:VLLM_MODEL)"
} else {
    $Mode = 'cpu'
    $ComposeFiles = $ComposeBase + @('-f', 'docker-compose.cpu.yml')
    $ollamaModel = if ($EnvVars['OLLAMA_MODEL']) { $EnvVars['OLLAMA_MODEL'] } else { 'qwen2.5:3b' }
    try { $ramGb = [math]::Round((Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory / 1GB) }
    catch { $ramGb = 0 }
    Info "LLM mode: CPU -> Ollama  model=$ollamaModel  RAM=${ramGb} GB"
    if ($ramGb -gt 0 -and $ramGb -lt 8) { Warn "Low RAM (${ramGb} GB). Consider OLLAMA_MODEL=qwen2.5:1.5b" }
}

# ─────────────────────────────────────────────────────────────────────────────
# 6 -- Dev services
# ─────────────────────────────────────────────────────────────────────────────
Step "6/9  Dev services (Prometheus + upf-sim + Grafana)"

if ($DevArg -eq 'yes') {
    $ComposeFiles += $DevCompose; Info "Dev services: enabled (-Dev)"
} elseif ($DevArg -eq 'no') {
    Info "Dev services: disabled (-NoDev)"
} elseif ([Environment]::UserInteractive) {
    Write-Host ""
    Write-Host "  Dev services add: upf-sim (simulated 5G UPF), Prometheus, Grafana."
    Write-Host "  Recommended for local testing. Skip for production (uses external Prometheus)."
    $choice = Read-Host "[run] Start dev services? [Y/n]"
    if (-not $choice -or $choice -match '^[Yy]') {
        $ComposeFiles += $DevCompose; Info "Dev services: enabled"
    } else {
        Info "Dev services: disabled"
    }
} else {
    $ComposeFiles += $DevCompose; Info "Dev services: enabled (non-interactive default)"
}

# ─────────────────────────────────────────────────────────────────────────────
# 7 -- Start stack
# ─────────────────────────────────────────────────────────────────────────────
Step "7/9  Starting Docker Compose stack"

$upCmd = $ComposeFiles + @('up', '--build', '-d') + $ExtraArgs
Info "docker compose $($upCmd -join ' ')"
& docker compose @upCmd

# ─────────────────────────────────────────────────────────────────────────────
# 8 -- Ollama model pull  (CPU mode only)
# ─────────────────────────────────────────────────────────────────────────────
Step "8/9  LLM model"

if ($Mode -eq 'cpu') {
    $ollamaModel = if ($EnvVars['OLLAMA_MODEL']) { $EnvVars['OLLAMA_MODEL'] } else { 'qwen2.5:3b' }
    Info "Waiting for Ollama (up to 2 min)..."
    $retries = 24
    while ($retries-- -gt 0) {
        & docker compose @ComposeFiles exec vllm ollama list 2>&1 | Out-Null
        if ($LASTEXITCODE -eq 0) { break }
        Start-Sleep 5
    }
    Info "Pulling $ollamaModel (first run: ~2 GB)..."
    & docker compose @ComposeFiles exec vllm ollama pull $ollamaModel
    Info "Ollama ready."
} else {
    Info "vLLM downloads model weights on first start (~5 GB)."
    Info "Track: docker compose logs -f vllm"
}

