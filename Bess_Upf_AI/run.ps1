# BESS-UPF AI — unified one-shot launcher (Windows PowerShell / pwsh)
#
# Does everything from a fresh clone:
#   1  Check prerequisites
#   2  Write .env with working defaults  (skips if already exists)
#   3  Generate dev TLS certificates     (skips if certs already exist)
#   4  Git LFS pull large model files    (skips if already present)
#   5  Detect GPU -> pick vLLM or Ollama, size model by VRAM
#   6  Ask: start dev services? (Prometheus + upf-sim + Grafana)
#   7  docker compose up --build -d
#   8  Pull Ollama model on first run    (CPU mode only)
#   9  Print access URLs and credentials
#
# Usage:
#   pwsh run.ps1           # interactive
#   pwsh run.ps1 -Dev      # always include dev services
#   pwsh run.ps1 -NoDev    # skip dev services (production / external Prometheus)
#
# Linux / macOS / Windows Git Bash: use bash run.sh instead.

param(
    [switch]$Dev,
    [switch]$NoDev,
    [Parameter(ValueFromRemainingArguments)][string[]]$ExtraArgs
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Push-Location $PSScriptRoot

function Info  { Write-Host "[run] $args" -ForegroundColor Green  }
function Warn  { Write-Host "[run] $args" -ForegroundColor Yellow }
function Err   { Write-Host "[run] ERROR: $args" -ForegroundColor Red }
function Step  { Write-Host "`n-- $args ----------------------------------------------------" -ForegroundColor Cyan }

$DevArg = if ($Dev) { 'yes' } elseif ($NoDev) { 'no' } else { '' }

# ─────────────────────────────────────────────────────────────────────────────
# 1 -- Prerequisites
# ─────────────────────────────────────────────────────────────────────────────
Step "1/9  Prerequisites"

function Need($cmd, $hint) {
    if (-not (Get-Command $cmd -ErrorAction SilentlyContinue)) {
        Err "$cmd not found.  $hint"; exit 1
    }
    Info "  OK $cmd"
}

Need docker  "Install Docker Desktop -> https://docs.docker.com/get-docker/"
Need openssl "Install OpenSSL (bundled with Git for Windows)."

& docker compose version 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) { Err "docker compose v2 not found. Upgrade Docker Desktop."; exit 1 }
Info "  OK docker compose (v2)"

$HasGitLfs = $false
if ((Get-Command git -ErrorAction SilentlyContinue) -and
    ((& git lfs version 2>&1) -match 'git-lfs')) {
    $HasGitLfs = $true; Info "  OK git lfs"
} else {
    Warn "  git lfs not installed -- random_forest.joblib (1.2 GB) won't auto-download."
    Warn "  Install: https://git-lfs.github.com  then re-run."
}

